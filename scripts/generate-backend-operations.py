"""Keep all four clients on the same first-party Lia API operation contract."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
ops = json.loads((root/'backends/contract.json').read_text())['operations']
mapped = {o['name']: o for o in ops}
(root/'packages/server/src/operations.ts').write_text('// Generated by scripts/generate-backend-operations.py.\nexport const operations = '+json.dumps(mapped,indent=2)+' as const;\n')
for language, folder in [('python','src/lia_server'), ('php','src'), ('go','')]:
    (root/'backends'/language/folder/'operations.json').write_text(json.dumps(mapped,indent=2)+'\n')
# Fail if a newly added operation has no public method; wrappers remain idiomatic, reviewed code.
for o in ops:
    for file in ['packages/server/src/index.ts','backends/php/src/LiaClient.php','backends/go/client.go']:
        if o['name'].lower() not in (root/file).read_text().lower():
            raise SystemExit(f"Missing wrapper for {o['name']} in {file}")
